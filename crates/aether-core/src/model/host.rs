#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", default)]
#[ts(export)]
pub struct Host {
    pub id: HostId,
    /// Display name. Falls back to the hostname.
    pub label: String,
    pub hostname: String,
    pub port: u16,
    /// Empty = use the default from Settings (or the Windows user name).
    pub username: String,
    pub group_id: Option<GroupId>,
    pub tags: Vec<String>,
    /// Accent colour (`#rrggbb`) shown beside the host.
    pub color: Option<String>,
    pub favorite: bool,
    pub notes: String,
    pub auth: AuthConfig,
    pub jump: Vec<JumpRef>,
    pub options: ConnectionOptions,
    pub forwards: Vec<ForwardRule>,
    pub startup: StartupConfig,
    pub terminal: TerminalOverride,
    pub origin: HostOrigin,
    /// Manual ordering inside its group.
    pub sort: i32,
    pub created_at: i64,
    pub updated_at: i64,
    pub last_connected_at: Option<i64>,
    pub connect_count: u32,
}

impl Default for Host {
    fn default() -> Self {
        let now = now_ms();
        Self {
            id: HostId::new(),
            label: String::new(),
            hostname: String::new(),
            port: 22,
            username: String::new(),
            group_id: None,
            tags: Vec::new(),
            color: None,
            favorite: false,
            notes: String::new(),
            auth: AuthConfig::default(),
            jump: Vec::new(),
            options: ConnectionOptions::default(),
            forwards: Vec::new(),
            startup: StartupConfig::default(),
            terminal: TerminalOverride::default(),
            origin: HostOrigin::Manual,
            sort: 0,
            created_at: now,
            updated_at: now,
            last_connected_at: None,
            connect_count: 0,
        }
    }
}

const MAX_TAGS: usize = 24;
const MAX_TAG_LEN: usize = 32;

impl Host {
    pub fn new(hostname: impl Into<String>) -> Self {
        Self { hostname: hostname.into(), ..Default::default() }
    }

    /// The name shown in lists.
    pub fn display_name(&self) -> &str {
        if self.label.trim().is_empty() { &self.hostname } else { &self.label }
    }

    /// `user@host[:port]`, the way people write it.
    pub fn target(&self) -> String {
        let mut s = String::new();
        if !self.username.is_empty() {
            s.push_str(&self.username);
            s.push('@');
        }
        if self.hostname.contains(':') {
            s.push('[');
            s.push_str(&self.hostname);
            s.push(']');
        } else {
            s.push_str(&self.hostname);
        }
        if self.port != 22 {
            s.push(':');
            s.push_str(&self.port.to_string());
        }
        s
    }

    /// Normalises user-entered fields in place (trims, dedupes tags, fills label).
    pub fn normalize(&mut self) {
        self.hostname = self.hostname.trim().to_string();
        // `[fe80::1]` is how an IPv6 address is written next to a port; the name itself has no brackets.
        if let Some(inner) = self.hostname.strip_prefix('[').and_then(|h| h.strip_suffix(']')) {
            self.hostname = inner.to_string();
        }
        self.username = self.username.trim().to_string();
        self.label = self.label.trim().to_string();
        if self.label.is_empty() {
            self.label = self.hostname.clone();
        }
        let mut seen = std::collections::HashSet::new();
        self.tags = self
            .tags
            .iter()
            .map(|t| t.trim().trim_start_matches('#').to_string())
            .filter(|t| !t.is_empty())
            .map(|t| t.chars().take(MAX_TAG_LEN).collect::<String>())
            .filter(|t| seen.insert(t.to_lowercase()))
            .take(MAX_TAGS)
            .collect();
        for f in &mut self.forwards {
            f.bind_host = f.bind_host.trim().to_string();
            f.dest_host = f.dest_host.trim().to_string();
        }
    }

    pub fn validate(&self) -> Result<()> {
        if self.hostname.trim().is_empty() {
            return Err(CoreError::invalid("hostname", "enter a hostname or IP address"));
        }
        if self.hostname.contains(char::is_whitespace) {
            return Err(CoreError::invalid("hostname", "must not contain spaces"));
        }
        if !is_valid_hostname(self.hostname.trim()) {
            return Err(CoreError::invalid(
                "hostname",
                "use a host name or IP address: letters, digits, dots and dashes (nothing else is a valid address)",
            ));
        }
        if self.port == 0 {
            return Err(CoreError::invalid("port", "choose a port between 1 and 65535"));
        }
        if self.username.contains(char::is_whitespace) {
            return Err(CoreError::invalid("username", "must not contain spaces"));
        }
        if self.options.keepalive_interval_secs > 0 && self.options.keepalive_max == 0 {
            return Err(CoreError::invalid("keepalive", "the maximum missed count must be at least 1"));
        }
        if self.jump.iter().any(|j| matches!(j, JumpRef::Host { host_id } if *host_id == self.id)) {
            return Err(CoreError::invalid("jump hosts", "a host cannot jump through itself"));
        }
        for f in &self.forwards {
            f.validate()?;
        }
        Ok(())
    }
}

