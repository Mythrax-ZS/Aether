#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "kebab-case")]
#[ts(export)]
pub enum AuthMethodKind {
    /// Keys held by a running ssh-agent (Windows OpenSSH agent or Pageant).
    Agent,
    /// A private key file or a key stored in Aether's vault.
    PublicKey,
    /// Server-driven challenge/response (2FA codes, PAM prompts).
    KeyboardInteractive,
    Password,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "kebab-case", rename_all_fields = "camelCase")]
#[ts(export)]
pub enum KeySource {
    /// A key file on disk, e.g. `C:\Users\me\.ssh\id_ed25519`.
    File { path: String },
    /// A key imported into, or generated by, Aether's secure vault.
    Vault { key_id: KeyId },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", default)]
#[ts(export)]
pub struct AuthConfig {
    /// Methods to try, in order. The server's own list is intersected with this.
    pub methods: Vec<AuthMethodKind>,
    /// Explicit key to use for public-key auth. When unset, the default identity
    /// files from Settings are tried.
    pub key: Option<KeySource>,
    /// Only offer the explicit key (like OpenSSH `IdentitiesOnly`); skip agent keys.
    pub identities_only: bool,
}

impl Default for AuthConfig {
    fn default() -> Self {
        Self {
            methods: vec![
                AuthMethodKind::Agent,
                AuthMethodKind::PublicKey,
                AuthMethodKind::KeyboardInteractive,
                AuthMethodKind::Password,
            ],
            key: None,
            identities_only: false,
        }
    }
}

/// One hop of a `ProxyJump` chain.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "type", rename_all = "kebab-case", rename_all_fields = "camelCase")]
#[ts(export)]
pub enum JumpRef {
    /// Another saved host (reuses its credentials and settings).
    Host { host_id: HostId },
    /// An ad-hoc `[user@]host[:port]` string, e.g. imported from `ProxyJump`.
    Adhoc { spec: String },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", default)]
#[ts(export)]
pub struct ConnectionOptions {
    pub connect_timeout_secs: u32,
    /// Seconds of silence before a keepalive is sent. `0` disables keepalives.
    pub keepalive_interval_secs: u32,
    /// Unanswered keepalives before the connection is declared dead.
    pub keepalive_max: u32,
    pub compression: bool,
    pub agent_forwarding: bool,
    pub x11_forwarding: bool,
    pub auto_reconnect: bool,
    /// `$TERM` requested for the PTY.
    pub term: String,
    /// Offer legacy algorithms (ssh-rsa, DH group14-sha1, CBC ciphers, SHA-1 MACs)
    /// for old network gear and embedded devices.
    pub legacy_algorithms: bool,
    /// Shell command used instead of a direct TCP connection (`ProxyCommand`).
    /// `%h` and `%p` expand to the target host and port.
    pub proxy_command: String,
}

impl Default for ConnectionOptions {
    fn default() -> Self {
        Self {
            connect_timeout_secs: 15,
            keepalive_interval_secs: 30,
            keepalive_max: 3,
            compression: false,
            agent_forwarding: false,
            x11_forwarding: false,
            auto_reconnect: true,
            term: "xterm-256color".into(),
            legacy_algorithms: false,
            proxy_command: String::new(),
        }
    }
}

