#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn target_formats_like_ssh() {
        let mut h = Host::new("example.com");
        assert_eq!(h.target(), "example.com");
        h.username = "root".into();
        h.port = 2222;
        assert_eq!(h.target(), "root@example.com:2222");
        h.hostname = "fe80::1".into();
        assert_eq!(h.target(), "root@[fe80::1]:2222");
    }

    #[test]
    fn normalize_fills_label_and_cleans_tags() {
        let mut h = Host::new("  db.internal ");
        h.tags = vec!["#prod".into(), "Prod".into(), " ".into(), "db".into()];
        h.normalize();
        assert_eq!(h.hostname, "db.internal");
        assert_eq!(h.label, "db.internal");
        assert_eq!(h.tags, vec!["prod", "db"]);
    }

    #[test]
    fn validation_rules() {
        let mut h = Host::new("example.com");
        assert!(h.validate().is_ok());
        h.hostname = "bad host".into();
        assert!(h.validate().is_err());
        // Things that are not addresses at all: a host name never carries wildcards, separators or shell syntax.
        for bad in ["*", "a*b", "a,b", "-oProxyCommand=x", "host&calc", "a/b", "|1|x|y"] {
            h.hostname = bad.into();
            assert!(h.validate().is_err(), "{bad}");
        }
        h.hostname = "ok".into();
        h.port = 0;
        assert!(h.validate().is_err());
        h.port = 22;
        h.jump = vec![JumpRef::Host { host_id: h.id }];
        assert!(h.validate().is_err());
    }

    #[test]
    fn old_files_missing_new_fields_still_load() {
        let json = r#"{ "id": "7d444840-9dc0-11d1-b245-5ffdce74fad2", "hostname": "x" }"#;
        let h: Host = serde_json::from_str(json).unwrap();
        assert_eq!(h.port, 22);
        assert!(h.options.auto_reconnect);
        assert_eq!(h.auth.methods.len(), 4);
    }

    #[test]
    fn key_source_is_tagged_camel_case() {
        let k = KeySource::Vault { key_id: KeyId::new() };
        let v = serde_json::to_value(&k).unwrap();
        assert_eq!(v["type"], "vault");
        assert!(v.get("keyId").is_some());
    }
}
